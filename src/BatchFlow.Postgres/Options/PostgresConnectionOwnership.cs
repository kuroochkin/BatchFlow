namespace BatchFlow.Postgres.Options;

/// <summary>
/// Определяет, кто отвечает за жизненный цикл переданного экземпляра <c>NpgsqlConnection</c>.
/// </summary>
public enum PostgresConnectionOwnership
{
    /// <summary>
    /// Подключением владеет вызывающий код.
    /// Адаптер не открывает, не закрывает и не освобождает этот экземпляр автоматически.
    /// </summary>
    External = 0,

    /// <summary>
    /// Подключением владеет адаптер.
    /// Адаптер при необходимости откроет его и освободит после завершения операции.
    /// </summary>
    /// <remarks>
    /// Для источника операция охватывает одно перечисление данных. Повторное перечисление с тем же экземпляром
    /// соединения не поддерживается. Хранилище контрольных точек отклоняет этот режим: ему нужны повторные операции.
    /// При ошибке открытия или отмене адаптер также освобождает переданный экземпляр.
    /// </remarks>
    AdapterOwned = 1,
}
